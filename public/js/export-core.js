/* ---------- Build ---------- */

/**
 * opts: { format: 'zip' | 'war', images, data, vendor }
 * Returns { blob, filename, name, warnings, count }.
 */
export async function buildExport(story, opts, io, brand, step = () => {}) {
  const name = slugify(story.title);
  step('Bundling the story reader');
  const reader = await bundleReader(io, brand);
  const [storyCss, mapCss] = await Promise.all([io.text('/css/story.css'), io.text('/css/map.css')]);
  const favicon = await io.text('/favicon.svg').catch(() => '');
  const { story: prepared, files, warnings } = await collect(story, opts, io, step);

  let vendored = false;
  const vendorFiles = [];
  if (opts.vendor) {
    step('Including the map library');
    try {
      const [js, css] = await Promise.all([io.remote(`${MAPLIBRE}.js`), io.remote(`${MAPLIBRE}.css`)]);
      vendorFiles.push({ path: 'vendor/maplibre-gl.js', data: js }, { path: 'vendor/maplibre-gl.css', data: css },
        { path: 'vendor/LICENSE-maplibre.txt', data: 'MapLibre GL JS is distributed under the BSD-3-Clause license.\nhttps://github.com/maplibre/maplibre-gl-js/blob/main/LICENSE.txt\n' });
      vendored = true;
    } catch { warnings.push('The map library could not be included; the export will load it from unpkg.com.'); }
  }

  step('Writing the files');
  const all = [
    { path: 'index.html', data: page(prepared, brand, { vendored }) },
    { path: 'js/waymark-story.js', data: reader },
    { path: 'css/story.css', data: storyCss },
    { path: 'css/map.css', data: mapCss },
    ...(favicon ? [{ path: 'favicon.svg', data: favicon }] : []),
    ...files,
    ...vendorFiles,
    { path: 'README.txt', data: readme(prepared, brand, name, opts.format) },
  ];
  if (opts.format === 'war') {
    all.push({ path: 'META-INF/MANIFEST.MF', data: `Manifest-Version: 1.0\r\nCreated-By: ${brand.name}\r\n\r\n` });
    all.push({ path: 'WEB-INF/web.xml', data: webXml(prepared.title || name) });
  }
  // A .zip gets one top-level folder so it unpacks tidily; a .war must not have one.
  const entries = opts.format === 'war' ? all : all.map((f) => ({ ...f, path: `${name}/${f.path}` }));
  return { blob: zip(entries), filename: `${name}.${opts.format === 'war' ? 'war' : 'zip'}`, name, warnings, count: all.length };
}
